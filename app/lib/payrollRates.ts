// ============ 源泉所得税(電算機計算の特例・甲欄) ============
// 支給日の属する「年」で適用する計算式が変わる。

/** 給与所得控除の月額(1円未満切上げ前の値を返す) */
function kyuyoShotokuKojo(A: number, taxYear: number): number {
  if (taxYear >= 2020) {
    // 令和2年分以降(給与所得控除の最低55万円)
    if (A <= 135416) return 45834;
    if (A <= 149999) return A * 0.4 - 8333;
    if (A <= 299999) return A * 0.3 + 6667;
    if (A <= 549999) return A * 0.2 + 36667;
    if (A <= 708330) return A * 0.1 + 91667;
    return 162500; // 上限195万円/12
  }
  if (taxYear >= 2017) {
    // 平成29〜31年分(最低65万円・上限220万円)
    if (A <= 135416) return 54167;
    if (A <= 149999) return A * 0.4;
    if (A <= 299999) return A * 0.3 + 15000;
    if (A <= 549999) return A * 0.2 + 45000;
    if (A <= 833333) return A * 0.1 + 100000;
    return 183334; // 上限220万円/12
  }
  // 平成28年分(上限230万円・年収1,200万円超)
  if (A <= 135416) return 54167;
  if (A <= 149999) return A * 0.4;
  if (A <= 299999) return A * 0.3 + 15000;
  if (A <= 549999) return A * 0.2 + 45000;
  if (A <= 833333) return A * 0.1 + 100000;
  if (A <= 1000000) return A * 0.05 + 141667;
  return 191667; // 上限230万円/12
}

/** 基礎控除の月額 */
function kisoKojo(A: number, taxYear: number): number {
  if (taxYear >= 2020) {
    // 令和2年分以降は高所得で逓減
    if (A <= 2162499) return 40000;
    if (A <= 2204166) return 26667;
    if (A <= 2245833) return 13334;
    return 0;
  }
  return 31667; // 平成28〜31年分(38万円/12)
}

/**
 * 月額給与の源泉徴収所得税(甲欄)。
 * @param afterShakaiHoken 社会保険料等控除後の給与等の金額
 * @param dependents 扶養親族等の数
 * @param taxYear 支給日の属する年
 */
export function calcWithholdingTax(afterShakaiHoken: number, dependents: number, taxYear: number): number {
  const A = afterShakaiHoken;
  if (A <= 0) return 0;

  const B = Math.ceil(kyuyoShotokuKojo(A, taxYear));
  const C = kisoKojo(A, taxYear);
  const D = 31667 * dependents; // 扶養控除等の月額(この期間は不変)

  const taxable = Math.max(0, A - B - C - D);
  if (taxable <= 0) return 0;

  // 月割の税額速算表(復興特別所得税込み。平成25年以降不変)
  let tax: number;
  if (taxable <= 162500) tax = taxable * 0.05105;
  else if (taxable <= 275000) tax = taxable * 0.1021 - 8296;
  else if (taxable <= 579166) tax = taxable * 0.2042 - 36374;
  else if (taxable <= 750000) tax = taxable * 0.23483 - 54113;
  else if (taxable <= 1500000) tax = taxable * 0.33693 - 130688;
  else if (taxable <= 3333333) tax = taxable * 0.4084 - 237893;
  else tax = taxable * 0.45945 - 408061;

  // 10円未満四捨五入
  return Math.max(0, Math.round(tax / 10) * 10);
}
