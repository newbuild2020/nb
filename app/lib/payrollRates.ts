/** 登録済みの最古・最新の協会けんぽ年度 */
export const KENPO_MIN_YEAR = 2016;
export const KENPO_MAX_YEAR = 2026;

/**
 * 勤務月 → 協会けんぽの適用年度。
 * 各年度の料率はその年の3月分から翌年2月分まで適用される。
 * 登録範囲外の将来月は最新年度にフォールバックする(isFallback=true)。
 */
export function kenpoFiscalYear(year: number, month: number): { fy: number; isFallback: boolean } {
  const fy = month >= 3 ? year : year - 1;
  if (fy > KENPO_MAX_YEAR) return { fy: KENPO_MAX_YEAR, isFallback: true };
  if (fy < KENPO_MIN_YEAR) return { fy: KENPO_MIN_YEAR, isFallback: true };
  return { fy, isFallback: false };
}

// ============ 厚生年金保険料率(%) ============

/**
 * 平成16年改正による段階引上げの最終期。9月分で改定。
 * 平成29年9月分以降は18.3%で固定。
 */
export function pensionRate(year: number, month: number): number {
  const ym = year * 12 + (month - 1);
  if (ym >= 2017 * 12 + 8) return 18.3;   // 2017年9月分〜
  if (ym >= 2016 * 12 + 8) return 18.182; // 2016年9月分〜2017年8月分
  return 17.828;                          // 2015年9月分〜2016年8月分
}

